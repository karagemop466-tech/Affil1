"""Render the independent-check annex through the publication's own layout.

Separated from `audit_canonical.py` so that tool can run as a plain script
(no layout imports, no build side effects) while the page itself is emitted by
`tools/build.py` exactly like every other page. That is what makes the annex
part of the edition rather than a hand-written file sitting next to it.
"""

from layout import esc, eyebrow, outbound, page, pagehead, rel, section


def render(page_dir, findings, stats, edition, session, tag):
    d = page_dir
    problems = [f for f in findings if f["severity"] in ("high", "medium")]
    passes = [f for f in findings if f["severity"] == "ok"]

    order = {"high": 0, "medium": 1, "low": 2, "ok": 3}
    rows = []
    for f in sorted(findings, key=lambda x: (order.get(x["severity"], 9), x["id"])):
        pill = {"high": "flag", "medium": "warn", "low": "mute", "ok": "ok"}.get(f["severity"], "mute")
        rows.append(
            f"<tr><td><span class=\"pill pill-{pill}\">{esc(f['severity'])}</span></td>"
            f"<td><code>{esc(f['id'])}</code></td>"
            f"<td><strong>{esc(f['title'])}</strong><br>"
            f"<span class=\"muted\">{esc(f['detail'])}</span></td></tr>"
        )
    findings_table = (
        '<div class="table-wrap"><table class="register">'
        "<thead><tr><th>Severity</th><th>Ref</th>"
        "<th>What was checked, and what was found</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )

    def stat_row(label, value):
        return (f"<tr><td>{esc(label)}</td><td><strong>{esc(value)}</strong></td></tr>")

    stats_block = (
        '<div class="table-wrap"><table class="register">'
        "<thead><tr><th>What was counted</th><th style=\"width:9rem\">Value</th></tr></thead><tbody>"
        + stat_row("Pages read", stats.get("indexable_pages", 0) + stats.get("noindex_pages", 0))
        + stat_row("Internal references resolved", f'{stats.get("internal_references", 0):,}')
        + stat_row("Broken references", stats.get("broken_references", 0))
        + stat_row("Amazon product links", stats.get("amazon_product_links", 0))
        + stat_row("… cited with no tag parameter", stats.get("tagged", 0))
        + stat_row("… missing rel=sponsored", stats.get("unsponsored", 0))
        + stat_row("Published commerce figures", stats.get("commerce_figure_hits", 0))
        + stat_row("Third-party scripts or pixels", stats.get("third_party_scripts", 0))
        + stat_row("Sitemap URLs", stats.get("sitemap_urls", 0))
        + stat_row("Feed items", stats.get("feed_items", 0))
        + "</tbody></table></div>"
    )

    body = f"""{pagehead(
        'Annex',
        'Independent check<br>of this edition',
        'A second pair of eyes on the same five products, run on 20 November 2026 by a session '
        'that did not build the pages it is checking. It re-reads the committed HTML rather than '
        'trusting any claim made about it, and it publishes what it found — including the findings '
        'this edition had not yet recorded.',
        meta=f'Reproducible &middot; <code>python3 tools/audit_canonical.py</code> &middot; session {session}',
    )}
{section(f'''<div class="callout">
  <h2>For the owner, in one paragraph</h2>
  <p>The edition is internally consistent: every internal reference resolves, every page carries the
  Associates statement before its main content, no price or rating is published anywhere, and the
  sitemap and feed are valid. The commercial gap that remains is single and deliberate — no Amazon
  product link on this site carries the Associates tag, because none can until an enrolled Special
  Link exists. That is recorded below rather than quietly fixed, because appending a tag to a
  listing URL is not the same as an enrolled link.</p>
</div>''', cls='')}
{section(f'''<div class="sec-head"><div>{eyebrow('Findings')}<h2>{len(problems)} problem finding(s), {len(passes)} check(s) passed</h2></div>
<p>Every row is regenerated by the build, so this page cannot drift from the edition it describes.</p></div>
{findings_table}''', cls='section-tint')}
{section(f'''<div class="sec-head"><div>{eyebrow('What was counted')}<h2>The numbers behind the table</h2></div>
<p>Counts are taken from the files on disk at build time, not from any claim the site makes about itself.</p></div>
{stats_block}''', cls='')}
{section(f'''<div class="lede-prose">
<h2>What this check did not do</h2>
<p>It did not sign in to the Associates account, so it cannot confirm attribution, commission rates,
or whether any click earns. It did not buy anything. It did not test any appliance — no appliance in
this set has been handled by anyone writing for this site, and every product claim in the edition is a
quotation from a listing title. It also did not re-verify the archived editions under
<code>archive/</code>: those are kept as historical records and are excluded from the published
staging step, not silently deleted.</p>

<h2>Method</h2>
<p>Every canonical HTML file is read from disk. Internal references are resolved against the
filesystem, with fragments and querystrings stripped. Amazon links are counted and inspected for
<code>rel</code> values and for the <code>tag=</code> parameter. Commerce figures are searched for by
pattern, with policy quotations excluded by their surrounding context. Sitemap and feed are parsed as
XML, then each URL is mapped back to a file. The register is read directly, and the
intended-versus-observed identifier split is asserted rather than assumed.</p>

<h2>Reproduce it</h2>
<p><code>python3 tools/audit_canonical.py</code> prints the same findings to a terminal without
writing anything. <code>python3 tools/build.py</code> regenerates this page from those findings, and
the build's own reproducibility step fails if the committed copy differs from the generated one.</p>
</div>''', cls='')}
"""

    return page(
        d,
        title="Independent check \u2014 Crisp & Counter",
        description=("A reproducible second-opinion audit of this edition: internal links, disclosure "
                     "placement, sponsored marking, tracking parameters, commerce figures, indexability."),
        body=body,
        active=None,
        index=False,
    )
