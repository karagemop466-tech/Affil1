#!/usr/bin/env python3
"""Enforce one published surface.

This repository has been rebuilt from scratch by several parallel sessions, each
of which produced its own front page, its own generator and its own data schema.
Six such surfaces had accumulated. Every one of them is preserved on disk under
`archive/` — nothing is deleted, because a reviewer has to be able to compare the
competing claims — but only the pages generated by `tools/build.py` may sit in the
published tree, because two index.html files at one URL is not a site, and two
build systems writing the same file is how a "verified" register quietly drifts.

Run after merging a branch that carried its own generated pages:

    python3 tools/build.py && python3 tools/sweep_surfaces.py && python3 tools/validate.py

Moved files keep their original path under
`archive/<this-run>/`, and `robots.txt` disallows `/archive/`, so the set-aside
pages stay reviewable without competing for indexing.
"""

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

ARCHIVE_ROOT = "archive"
PUBLISHED_DIRS = ["guides", "compare", "products", "about", "sources", "suggestions",
                  "questions", "flagged", "legacy", "topics", "dashboard"]
PUBLISHED_FILES = {"index.html", "404.html", "feed.xml", "sitemap.xml", "robots.txt"}


def published_set():
    """Exactly the paths tools/build.py writes, read from the generator itself."""
    keep = set(PUBLISHED_FILES)
    try:
        import build  # noqa: F401
        slugs = list(build.GUIDES.keys())
    except Exception as exc:  # noqa: BLE001 - the builder is optional for a dry run
        print(f"note: could not import tools/build.py ({exc}); keeping guides by directory")
        slugs = None
    if slugs:
        keep |= {f"guides/{s}/index.html" for s in slugs}
    keep.add("guides/index.html")
    for d in PUBLISHED_DIRS:
        keep.add(f"{d}/index.html")
    return keep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-label", default="set-aside", help="archive subfolder name")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    keep = published_set()
    dest = f"{ARCHIVE_ROOT}/{args.run_label}"
    moved = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT).as_posix()
        parts = set(path.relative_to(ROOT).parts)
        if ARCHIVE_ROOT in parts or rel in keep:
            continue
        # only sweep generated surfaces and their assets: source, tools and docs stay
        top = rel.split("/", 1)[0]
        if top not in PUBLISHED_DIRS and path.suffix not in {".html", ".xml"}:
            continue
        if top in PUBLISHED_DIRS and not rel.endswith(".html"):
            continue
        moved.append(rel)
        if not args.dry_run:
            target = f"{dest}/{rel}"
            pathlib.Path(f"{ROOT}/{dest}").mkdir(parents=True, exist_ok=True)
            tracked = subprocess.run(["git", "ls-files", "--error-unmatch", rel],
                                     cwd=ROOT, capture_output=True).returncode == 0
            if tracked:
                subprocess.run(["git", "mv", "-f", rel, target], check=True, cwd=ROOT)
            else:
                import shutil
                pathlib.Path(f"{ROOT}/{dest}/{rel}").parent.mkdir(parents=True, exist_ok=True)
                shutil.move(str(ROOT / rel), f"{ROOT}/{dest}/{rel}")
                subprocess.run(["git", "add", "-f", f"{dest}/{rel}"], cwd=ROOT, capture_output=True)

    if not args.dry_run:
        for d in sorted((p for p in ROOT.rglob("*") if p.is_dir()), reverse=True):
            if ARCHIVE_ROOT in d.parts or d.name in {".git", "tools", "src", "assets"}:
                continue
            if not any(d.iterdir()):
                d.rmdir()
        note = pathlib.Path(ROOT) / dest / "README.md"
        if moved:
            note.parent.mkdir(parents=True, exist_ok=True)
            if not note.exists():
                note.write_text(
                    "# Set aside by `tools/sweep_surfaces.py`\n\n"
                    "Pages generated by a parallel session that competed with the published "
                    "surface. Preserved verbatim, never edited, disallowed in robots.txt and absent "
                    "from the sitemap. Compare them against the published build in `tools/` and "
                    "`src/data/` if a decision turns on their contents.\n\nFiles:\n\n"
                    + "".join(f"- `{m}`\n" for m in moved),
                    encoding="utf-8",
                )

    print(f"published surface: {len(keep)} pages")
    print(f"{'would move' if args.dry_run else 'moved'}: {len(moved)} file(s) -> {dest}/")
    for m in moved:
        print("   ", m)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
