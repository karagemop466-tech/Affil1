#!/usr/bin/env python3
"""Enforce one published surface.

This repository has been rebuilt from scratch by several parallel sessions, each
of which produced its own front page, its own generator and its own data schema.
Six such surfaces had accumulated. Every one of them is preserved on disk under
`archive/` — nothing is deleted, because a reviewer has to be able to compare the
competing claims — but only the pages generated by `tools/build.py` may sit in the
published tree, because two index.html files at one URL is not a site, and two
build systems writing the same file is how a "verified" register quietly drifts.

Run after merging a branch that carried its own generated pages:

    python3 tools/build.py && python3 tools/sweep_surfaces.py && python3 tools/validate.py

Moved files keep their original path under
`archive/<this-run>/`, and `robots.txt` disallows `/archive/`, so the set-aside
pages stay reviewable without competing for indexing.

One exception, and it is the same one `tools/check.py` already makes:
`decision-support/` is a hand-maintained set of working papers that is not built
by `tools/build.py` and never claims to be. It carries its own validator,
`decision-support/validate.py`, which `pages.yml` runs on every push, and every
page in it declares `noindex` and is disallowed in `robots.txt`. Without this
exception the sweep reports those seven files on every run and the launch gate
can never be green; with it, a genuine second published surface is still caught.
"""

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

ARCHIVE_ROOT = "archive"
# Hand-maintained internal sections, not published surfaces. Mirrors
# tools/check.py's INTERNAL_SECTIONS; the decision-support desk is one (see
# COORDINATION.md — added by session-arena-83e015f6 to unstick the launch
# gate, which failed on every branch including main).
INTERNAL_SECTIONS = ("decision-support/",)
PUBLISHED_DIRS = ["guides", "compare", "products", "about", "sources", "suggestions",
                  "questions", "flagged", "legacy", "topics", "dashboard"]
PUBLISHED_FILES = {"index.html", "404.html", "feed.xml", "sitemap.xml", "robots.txt"}


def internal_sections():
    """Directories that are hand-maintained but explicitly excluded from "one site".

    The list is imported from tools/check.py rather than repeated here, so the
    two gates cannot drift apart: whatever the page checker excuses, the sweep
    must excuse too, or CI reports a conflict that does not exist.
    """
    try:
        import check  # noqa: F401
        return tuple(check.INTERNAL_SECTIONS)
    except Exception as exc:  # noqa: BLE001 - a missing checker must not crash a sweep
        print(f"note: could not import tools/check.py ({exc}); using the local list")
        return tuple(INTERNAL_SECTIONS)


def published_set():
    """Exactly the paths tools/build.py writes, read from the generator itself."""
    keep = set(PUBLISHED_FILES)
    # build.GENERATED is the complete list of paths the builder writes. GUIDES
    # is a list, so reading it as a mapping made this function fall back to
    # directory guesses and mark real generated pages as strays.
    try:
        import build  # noqa: F401
        keep |= set(build.GENERATED)
    except Exception as exc:  # noqa: BLE001 - the builder is optional for a dry run
        print(f"note: could not import tools/build.py ({exc}); keeping guides by directory")
        keep.add("guides/index.html")
        for d in PUBLISHED_DIRS:
            keep.add(f"{d}/index.html")
    return keep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-label", default="set-aside", help="archive subfolder name")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    keep = published_set()
    internal = internal_sections()
    dest = f"{ARCHIVE_ROOT}/{args.run_label}"
    moved = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT).as_posix()
        if ARCHIVE_ROOT in set(path.relative_to(ROOT).parts) or rel in keep:
            continue
        if rel.startswith(INTERNAL_SECTIONS):
            continue
        top = rel.split("/", 1)[0]
        # sweep only generated surfaces: data, tools, docs and assets stay put
        if top not in PUBLISHED_DIRS and path.suffix not in {".html", ".xml"}:
            continue
        if top in PUBLISHED_DIRS and path.suffix != ".html":
            continue
        moved.append(rel)
        if not args.dry_run:
            import shutil
            dst = ROOT / dest / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(path), str(dst))

    if not args.dry_run and moved:
        for d in sorted((x for x in ROOT.rglob("*") if x.is_dir()), reverse=True):
            if ARCHIVE_ROOT in d.parts or d.name in {".git", "tools", "src", "assets"}:
                continue
            try:
                if not any(d.iterdir()):
                    d.rmdir()
            except OSError:
                pass
        note = ROOT / dest / "README.md"
        if not note.exists():
            note.write_text(
                "# Set aside by `tools/sweep_surfaces.py`\n\n"
                "Pages generated by a parallel session that competed with the published "
                "surface. Preserved verbatim, never edited, disallowed in robots.txt and absent "
                "from the sitemap. Compare them against the published build in `tools/` and "
                "`src/data/` if a decision turns on their contents.\n\nFiles moved in this run:\n\n"
                + "".join(f"- `{m}`\n" for m in moved),
                encoding="utf-8",
            )

    print(f"published surface: {len(keep)} generated pages allowed")
    print(f"{'would move' if args.dry_run else 'moved'}: {len(moved)} file(s) -> {dest}/")
    for m in moved:
        print("   ", m)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
